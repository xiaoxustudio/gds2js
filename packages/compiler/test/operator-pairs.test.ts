const H = "extends SceneTree\n\n";
const OPS_CODE = /^(op-pair|op-mod-float|op-eq-cross-type|bool-ordering)$/;

function srcOf(expr: string): string {
  if (!expr.startsWith("VAR|") && !expr.startsWith("CONST|")) return H + "func f():\n\tprint(" + expr + ")\n";
  const [tag, lt, ltLit, op, rtLit] = expr.split("|");
  const kw = tag === "CONST" ? "const K" : "var a";
  const lhs = tag === "CONST" ? "K" : "a";
  return `extends SceneTree\n\n${kw}: ${lt} = ${ltLit}\n\nfunc f():\n\tprint(${lhs} ${op} ${rtLit})\n`;
}

async function first(expr: string): Promise<string> {
  const diags = analyze(lower(await parseSource(srcOf(expr))));
  const d = diags.find((x) => OPS_CODE.test(x.code));
  return d?.message ?? "不拦";
}

