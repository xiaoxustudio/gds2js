async function run(what: string, cells: Array<[string, string | null]>, code: string): Promise<void> {
  let bad = 0;
  let firstBad = "";
  for (const [expr, want] of cells) {
    const key = /^[VAR|CONST]\|/.test(expr) ? expr.split("|").slice(1).join(" ") : expr;
    let got = "";
    try {
      got = await first(expr);
    } catch (e) {
      got = "抛 " + (e instanceof Error ? e.message : String(e));
    }
    if (got !== (want ?? "不拦")) {
      bad++;
      if (firstBad === "") firstBad = `${key}：期望 ${String(want ?? "不拦")}，实得 ${got}`;
    }
  }
  eq(code, `${what} ${String(cells.length)} 格不合数`, bad + (bad > 0 ? ` 首格[${firstBad}]` : ""), 0);
}

describe("运算符 × 型对", () => {
  it("两侧都是字面量：逐格对引擎", async () => run("字面量", LIT_CELLS, "394"));
  it("左支是标明类型的 var / 形参 / 内部类字段：逐格对引擎", async () => run("声明左支", DECL_CELLS, "395"));
  it("左支是模块级 const：逐格对引擎", async () => run("const 左支", CONST_CELLS, "396"));
});
