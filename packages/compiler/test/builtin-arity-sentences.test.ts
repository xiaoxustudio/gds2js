/**
 * 全局函数**元数两句**的逐名读数门（S365）：208 格句子逐字钉引擎（一名两格：少一元、多一元）。
 * 尺 `tmp/probe-argtype/fold49.mts`（每名试「出货最远位 +1 / +2」收上界）、`fold50.mts`（同支的「省掉这一位 / 给这一位」对照）、
 * `fold51.mts`（对上界的每名补「少一元」那一格，两句这才齐），读数 `tmp/aritymax/{readings.txt,both-ends.txt,optional.txt}`；
 * 一格一份脚本 —— 这两句都是解析期拒，一句废整份探针。
 * 要紧的一条：这批 utility 函数在 4.6.3 **没有默认实参** —— `ease` / `pingpong` / `is_equal_approx` / `type_exists` / `var_to_str` /
 * `inst_to_dict` 多给一位就是 `Too many arguments …`，所以缺的不是「丢实参的错值」而是**闸门**：这些名字多数不在 `BUILTIN_ARITY` 上，
 * 多给实参今天编得过、按最远那几位发出去。
 */
import { describe, expect, it } from "vitest";
import { analyze } from "@gds2js/compiler/lower/analyze";
import { lower } from "@gds2js/compiler/lower/lower";
import { parseSource } from "@gds2js/compiler/parse/parser";

async function sentence(call: string): Promise<string> {
  // S387 起这两句出自 analyze（引擎本来就是解析期拒）：探针跟着搬到那一段，句子文本一格没改。
  const src = `extends SceneTree\n\nfunc _initialize():\n\tprint(${call})\n\tquit()\n`;
  const hit = analyze(lower(await parseSource(src))).diagnostics.find((d) => /^Too (few|many) arguments for /.test(d.message));
  return hit?.message ?? "居然编得过";
}

