// Vector2 / Vector3 分量的打印位数（语料 301 逐字节钉了 11 行；这一门补语料里塞不下的边界形状，
// 并挡住「把小数位写回固定 6 位」那一类回退）。
// 读数：`tmp/probe-edge/{ladder,ladder2,ladder3}.gd` 与 `corpus/cases/301-float32-print-band/`。
import { describe, it } from "vitest";
import { eq } from "@gds2js/testkit";
import { strVec2 } from "@gds2js/runtime/runtime/string-ops";

const P = (n: number): string => strVec2(Math.fround(n));

describe("runtime · Vector 分量的打印位数随量级收缩", () => {
  it("小数位 = 6 - trunc(log10)，夹在 0..6", () => {
    eq("301", "|x| < 1 一律封顶 6 位", `${P(0.1234567)}|${P(0.001234567)}|${P(0.000123456)}`, "0.123457|0.001235|0.000123");
    eq("301", "1..10 给 6 位，10..100 给 5 位，100..1000 给 4 位", `${P(1.234567)}|${P(12.34567)}|${P(123.4567)}|${P(1234.567)}`, "1.234567|12.34567|123.4567|1234.567");
    eq("301", "1e4 给 2 位、1e5 给 1 位", `${P(12345.67)}|${P(31622.776)}|${P(123456.7)}|${P(577777.7)}`, "12345.67|31622.78|123456.7|577777.7");
    eq("301", "1e6 起给 0 位", `${P(2777777.7)}|${P(3430000.75)}|${P(-1234567.891)}`, "2777778|3430001|-1234568");
  });

  it("量级那一折是 float32 的 log10，进到上一档就跟着进位", () => {
    eq("301", "999999.875 与 1000000.375 都给 1000000（不是 999999.9）", `${P(999999.9)}|${P(1000000.4)}`, "1000000|1000000");
    eq("301", "9999.9995 进到 10000.0（小数位一起从 3 掉到 2）", P(9999.9999), "10000.0");
    eq("301", "199999.25 舍到 1 位是 half-away", P(199999.25), "199999.3");
  });

  it("`.0` 只由分量本身的值是否整数决定", () => {
    eq("301", "整数值带 .0，非整数值舍到 0 位不带", `${P(3430000.75)}|${P(3430001)}`, "3430001|3430001.0");
    eq("301", "字面量舍成整数就走整数展开", `${P(1234567.0625)}|${P(123456789.5)}|${P(6377777.75)}`, "1234567.0|123456792.0|6377778.0");
    eq("301", "舍到零的非零值给 0.0，负的那支留号", `${P(1e-20)}|${P(-0.0000005)}`, "0.0|-0.0");
  });
});
