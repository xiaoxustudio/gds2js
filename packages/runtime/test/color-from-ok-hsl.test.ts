describe("Color.from_ok_hsl 的形状", () => {
  it("l 满 / l 零两支短路，四通道一起夹进 0..1", () => {
    expect(chans("from_ok_hsl", [V.float(0.3), V.float(1), V.float(1)]).join(",")).toBe("1,1,1,1");
    expect(chans("from_ok_hsl", [V.float(0.3), V.float(1), V.float(0)]).join(",")).toBe("0,0,0,1");
    const up = chans("from_ok_hsl", [V.float(0), V.float(1), V.float(0.5)]);
    expect(Object.is(up[1], 0)).toBe(true);
    expect(up[0]! <= 1).toBe(true);
  });

  it("alpha 同样夹，但 -0 留号、nan 原样", () => {
    expect(chans("from_ok_hsl", [V.float(0.7), V.float(1), V.float(0.4), V.float(-0.2)])[3]).toBe(0);
    expect(chans("from_ok_hsl", [V.float(0.9), V.float(1), V.float(0.4), V.float(2)])[3]).toBe(1);
    expect(chans("from_ok_hsl", [V.float(0.9), V.float(1), V.float(0.4), V.float(Infinity)])[3]).toBe(1);
    expect(Number.isNaN(chans("from_ok_hsl", [V.float(0.33), V.float(1), V.float(0.4), V.float(NaN)])[3]!)).toBe(true);
    expect(Object.is(chans("from_ok_hsl", [V.float(0.6), V.float(0.25), V.float(0.4), V.float(-0)])[3], -0)).toBe(true);
  });

  it("第一参是圈：1.25 与 0.25 同值、-0.25 与 0.75 同值，2 与 0 却差在末位", () => {
    const f = (h: number): string => chans("from_ok_hsl", [V.float(h), V.float(0.5), V.float(0.5)]).map(fix).join("|");
    expect(f(1.25)).toBe(f(0.25));
    expect(f(-0.25)).toBe(f(0.75));
    expect(f(-1)).toBe(f(0));
    expect(f(2)).not.toBe(f(0));
  });

  it("int / bool 实参收下并折成数", () => {
    expect(chans("from_ok_hsl", [V.int(0), V.int(1), V.int(1)]).join(",")).toBe("1,1,1,1");
    expect(chans("from_ok_hsl", [V.bool(true), V.bool(true), V.bool(true)]).join(",")).toBe("1,1,1,1");
    expect(chans("from_ok_hsl", [V.bool(false), V.bool(true), V.bool(false)]).join(",")).toBe("0,0,0,1");
    expect(() => chans("from_ok_hsl", [V.str("a"), V.float(1), V.float(1)])).toThrow();
  });

  it("实例形是静态调用：给出新色，接收者不动", () => {
    const c = color(0.2, 0.3, 0.4, 0.5);
    const args = [V.float(0.1), V.float(1), V.float(0.5)];
    const ret = asColor(method(c, "from_ok_hsl", args))!;
    const st = asColor(colorStatic("from_ok_hsl", args))!;
    expect([ret.r, ret.g, ret.b, ret.a].map(fix).join("|")).toBe([st.r, st.g, st.b, st.a].map(fix).join("|"));
    expect([asColor(c)!.r, asColor(c)!.g, asColor(c)!.b, asColor(c)!.a]).toEqual([Math.fround(0.2), Math.fround(0.3), Math.fround(0.4), Math.fround(0.5)]);
  });

  it("元数只量过 3 / 4", () => {
    expect(() => colorStatic("from_ok_hsl", [V.float(1), V.float(1)])).toThrow(/需要 3 或 4 个参数/);
    expect(() => colorStatic("from_ok_hsl", [V.float(1), V.float(1), V.float(1), V.float(1), V.float(1)])).toThrow(/需要 3 或 4 个参数/);
  });
});
