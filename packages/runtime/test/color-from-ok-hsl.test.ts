function mk(tok: string): Variant {
  if (tok === "NAN") return V.float(NaN);
  if (tok === "INF") return V.float(Infinity);
  if (tok === "-INF") return V.float(-Infinity);
  if (tok === "true") return V.bool(true);
  if (tok === "false") return V.bool(false);
  return /^[+-]?\d+$/.test(tok) ? V.int(Number(tok)) : V.float(Number(tok));
}

const fix = (x: number): string => (Number.isNaN(x) ? "nan" : x.toFixed(9));

function chans(name: string, args: Variant[]): number[] {
  const c = asColor(colorStatic(name, args))!;
  return [c.r, c.g, c.b, c.a];
}

function run(line: string): [string, string[], string[]] {
  const sep = line.indexOf("|");
  const argStr = line.slice(0, sep);
  const want = line.slice(sep + 1).split("|");
  return [argStr, chans("from_ok_hsl", argStr.split(",").map(mk)).map(fix), want];
}

