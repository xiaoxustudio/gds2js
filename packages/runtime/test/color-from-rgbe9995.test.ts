/**
 * `Color.from_rgbe9995(packed)`：24 格的期望全部是 4.6.3 实测（一段脚本一次跑完，`tmp/probe-argtype/rgbe.mts` → `rgbe.txt`）。
 * 式子抄自 `core/math/color.cpp` 的 `Color::from_rgbe9995(uint32_t)`，装箱实参先折进 uint32 那一步也在同一批格子里钉住。
 */
import { describe, expect, it } from "vitest";
import { colorStatic } from "@gds2js/runtime/runtime/color";
import { show } from "@gds2js/runtime/runtime/values";
import { V } from "@gds2js/runtime/runtime/tags";

const CELLS: Array<[string, number | bigint, string]> = [
  ["0", 0n, "(0.0, 0.0, 0.0, 1.0)"],
  ["1", 1n, "(0.0, 0.0, 0.0, 1.0)"],
  ["511", 511n, "(0.0, 0.0, 0.0, 1.0)"],
  ["0x7FFFF（r=511,g=511,b=0,e=1）", 524287n, "(0.0, 0.0, 0.0, 1.0)"],
  ["0x80000（b=2,e=0）", 524288n, "(0.0, 0.0, 0.0, 1.0)"],
  ["0x1FFFFFF（三位全 511,e=0）", 33554431n, "(0.0, 0.0, 0.0, 1.0)"],
  ["0xFFFFFFFF（全 511,e=31）", 4294967295n, "(65408.0, 65408.0, 65408.0, 1.0)"],
  ["r=1,g=2,b=3,e=15", 1 + (2 << 9) + (3 << 18) + (15 << 27), "(0.002, 0.0039, 0.0059, 1.0)"],
  ["三位全 511,e=15", 511 + (511 << 9) + (511 << 18) + (15 << 27), "(0.998, 0.998, 0.998, 1.0)"],
  ["r=1,e=0（与 1 同格）", 1n, "(0.0, 0.0, 0.0, 1.0)"],
  ["r=1,e=255（int64 折 uint32）", BigInt(1) + (BigInt(255) << 27n), "(128.0, 0.0, 0.0, 1.0)"],
  ["r=511,e=255", BigInt(511) + (BigInt(255) << 27n), "(65408.0, 0.0, 0.0, 1.0)"],
  ["只有 e=127", BigInt(127) << 27n, "(0.0, 0.0, 0.0, 1.0)"],
  ["r=100,g=200,b=300,e=20", 100 + (200 << 9) + (300 << 18) + (20 << 27), "(6.25, 12.5, 18.75, 1.0)"],
  ["g=1,b=2,e=9", (1 << 9) + (2 << 18) + (9 << 27), "(0.0, 0.0, 0.0001, 1.0)"],
  ["-1（折成 0xFFFFFFFF）", -1n, "(65408.0, 65408.0, 65408.0, 1.0)"],
  ["-1 & 0xFFFFFFFF", BigInt(-1 & 0xffffffff), "(65408.0, 65408.0, 65408.0, 1.0)"],
  ["4294967296（2^32 → 全零）", 4294967296n, "(0.0, 0.0, 0.0, 1.0)"],
  ["4294967295", 4294967295n, "(65408.0, 65408.0, 65408.0, 1.0)"],
  ["2147483648（2^31）", 2147483648n, "(0.0, 0.0, 0.0, 1.0)"],
  ["2147483647（e=15、三位全 511）", 2147483647n, "(0.998, 0.998, 0.998, 1.0)"],
  ["1 << 40", 1n << 40n, "(0.0, 0.0, 0.0, 1.0)"],
];

describe("Color.from_rgbe9995", () => {
  it.each(CELLS)("%s", (_label, packed, expected) => {
    expect(show(colorStatic("from_rgbe9995", [V.int(packed)]))).toBe(expected);
  });
});
