#!/usr/bin/env node
/**
 * 把 gds2js 自己编成不带 node 的原生 exe：复制 src/ 与 packages/ 到 scratch、把四份同名文件换成原生实现、
 * 跑 scriptc build。解析器是纯 TS（手写递归下降），这条路上没有 C、没有 FFI、没有 wasm。
 *
 * 用法：
 *   node tools/cli-native.mjs                    # 出货形态：岛（scriptc 0.3.2 起是默认），编出来在 tmp/cli-native/gds2js.exe
 *   node tools/cli-native.mjs --keep             # 保留 scratch 树
 *   node tools/cli-native.mjs --coverage         # 只要围栏清单（带 file:line）
 */
import { spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync, existsSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { TREE_FACE } from "../packages/compiler/src/tree-face.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCRATCH = join(ROOT, "tmp", "cli-native");
const SCRIPTC = process.env.SCRIPTC_BIN ?? "scriptc";
const coverageOnly = process.argv.includes("--coverage");
const keep = process.argv.includes("--keep");

function fail(msg) {
  console.error(msg);
  process.exit(1);
}

function listTs(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) {
      // 测试面不进 exe：packages/*/test/ 是 Vitest 的测试（见 README「测试」—— 测试文件
      // 一律不放进 src/，因为 copyTreeTs 会扫 src/ 进出货产物树；这里 listTs 是第二条
      // 会扫到 test/ 的路径）。它们 import `vitest` 与 @gds2js/testkit，两者都不在
      // 步骤 2c 的相对化目标里（那个循环只认 runtime/compiler/gds2js 三包），
      // 落进 scratch 就会被 133 行「还剩没相对化的 @gds2js 说明符」判成构建失败。
      if (name === "test") continue;
      listTs(p, out);
    } else if (name.endsWith(".ts")) out.push(p);
  }
  return out;
}

/* 1) scratch 里的源码树：三个 workspace 包（packages/*）原样铺出来。
 *    包源码放在 SCRATCH/packages/*，步骤 2c 会把全部 `@gds2js/*` 说明符改成相对路径 ——
 *    盘面上一旦落进 node_modules，scriptc 会把它当「包代码」收进岛，这些源码必须保持静态编译。 */
rmSync(join(SCRATCH, "packages"), { recursive: true, force: true });
const pkgFiles = [];
for (const pkg of ["runtime", "compiler", "gds2js"]) {
  for (const abs of listTs(join(ROOT, "packages", pkg))) {
    const rel = relative(ROOT, abs).split("\\").join("/");
    const dest = join(SCRATCH, rel);
    mkdirSync(dirname(dest), { recursive: true });
    copyFileSync(abs, dest);
    pkgFiles.push(dest);
  }
}
console.log(`复制了 ${pkgFiles.length} 份包源码 → ${SCRATCH}`);

/* 2) 四份 seam 文件同名换实现：拿仓库里的 .native.ts 覆盖到 scratch 的同名位置。
 *    这是构建期分岔的口子：node 那侧吃进程内 import()、tsdown、SEA 资产，
 *    原生 exe 里这三样都不存在，所以同名换实现，其余源码一行不改。 */
const SEAMS = [
  ["packages/compiler/src/compile/ir-cache.native.ts", "packages/compiler/src/compile/ir-cache.ts"],
  ["packages/gds2js/src/bundle.native.ts", "packages/gds2js/src/bundle.ts"],
  ["packages/gds2js/src/exec.native.ts", "packages/gds2js/src/exec.ts"],
  ["packages/compiler/src/home.native.ts", "packages/compiler/src/home.ts"],
];
for (const [from, to] of SEAMS) copyFileSync(join(ROOT, from), join(SCRATCH, to));
console.log(`scratch 的 ${SEAMS.length} 份 seam 换成原生实现（${SEAMS.map(([, to]) => basename(to).replace(".ts", "")).join(" / ")}）`);

/* 原生那支的「自带家目录」= 构建期把 dist 与 runtime 源码嵌进 exe。
 * 契约与 SEA 那支一字不差：解出一个只读目录，给目录本身和目录里某个文件的落盘路径。
 * 键名与源位置全部来自 tree-face 清单（home/repo 两节），cli.ts 问 selfFile() 的那些键在这份清单里有唯一出处。 */
const HOME = [];
const HOME_KEYS = [];
function assetTo(rel, abs) {
  HOME_KEYS.push(rel);
  HOME.push(`  ${JSON.stringify(rel)}: ${JSON.stringify(readFileSync(abs, "utf8"))}`);
}
for (const name of readdirSync(join(ROOT, "packages", "gds2js", "dist")).sort()) {
  if (!/\.(mjs|cjs)$/.test(name)) continue;
  assetTo(`${TREE_FACE.home.distDir}/${name}`, join(ROOT, "packages", "gds2js", "dist", name));
}
const RT_SRC = join(ROOT, TREE_FACE.repo.runtimeSrcRoot);
const RT_DIR = join(RT_SRC, TREE_FACE.repo.runtimeDir);
for (const abs of listTs(RT_DIR)) assetTo(`${TREE_FACE.home.runtimeDir}/${relative(RT_DIR, abs).split("\\").join("/")}`, abs);
assetTo(TREE_FACE.home.host, join(RT_SRC, TREE_FACE.repo.host));
assetTo(TREE_FACE.home.sharedDouble, join(RT_SRC, TREE_FACE.repo.sharedDouble));
if (HOME.length === 0) fail("`dist` 里没有 .mjs/.cjs —— 先跑 pnpm build（原生 exe 要把自带运行时嵌进去）。");
const EMBED_MB = (HOME.reduce((n, s) => n + s.length, 0) / 1048576).toFixed(2);
/* 2b) 内嵌家目录的资产表：真实数据生成到 scratch 的 home-assets.gen.ts（scratch 的 home.ts 就是
 *     home.native.ts，它吃这份；仓库里那份只是空占位）。 */
writeFileSync(
  join(SCRATCH, "packages", "compiler", "src", "home-assets.gen.ts"),
  [
    "// AUTO-GENERATED by tools/cli-native.mjs（构建期覆写，别手改）：内嵌家目录的资产表。",
    "export const HOME_ASSETS: Readonly<Record<string, string>> = {",
    HOME.join(",\n"),
    "};",
    "",
    "export const HOME_KEYS: readonly string[] = [",
    HOME_KEYS.map((k) => `  ${JSON.stringify(k)}`).join(",\n"),
    "];",
    "",
  ].join("\n"),
  "utf8",
);
console.log(`scratch 的家目录资产生成（嵌 ${HOME.length} 份 / 约 ${EMBED_MB} MB 文本）`);

/* 2c) 相对化：scratch 里所有 `@gds2js/*` 说明符改成指向 SCRATCH/packages/* 的相对路径。
 *     一律不落 node_modules —— 那里被 scriptc 当「包代码」（要岛），而这些源码必须在静态 tier。 */
let relRewrites = 0;
for (const f of pkgFiles) {
  let s = readFileSync(f, "utf8");
  const before = s;
  s = s.replace(/"@gds2js\/(runtime|compiler)\/([^"]+)"/g, (m, pkg, rest) => {
    const hit = [join(SCRATCH, "packages", pkg, "src", rest + ".ts"), join(SCRATCH, "packages", pkg, "src", rest, "index.ts")].find((p) => existsSync(p));
    if (hit === undefined) fail(`scratch 里解析不了 ${m}（${f}）`);
    let rel = relative(dirname(f), hit).split("\\").join("/");
    if (!rel.startsWith(".")) rel = "./" + rel;
    return `"${rel}"`;
  });
  if (s !== before) {
    writeFileSync(f, s, "utf8");
    relRewrites++;
  }
  if (/"(?:@gds2js)\//.test(s)) fail(`scratch 里还剩没相对化的 @gds2js 说明符（${f}）`);
}
console.log(`相对化了 ${relRewrites} 份 scratch 源码的 @gds2js/* 说明符`);

/* 3) scriptc */
const entry = join(SCRATCH, "packages", "gds2js", "src", "cli.ts");
/* 岛是**必需**的，不再是可选形态：CLI 的参数解析用 commander，而 commander 不带岛就是 6 格 SC2013
 * （实测；岛里 0 错并真跑通）。原先 `--static` 那一支随 commander 一起没了。
 * scriptc 0.3.2 删了 `--dynamic`（选项表里已无此开关，岛是默认；`--npm-static` 反过来才是要静态吞包）——
 * 这里不再传它。 */
if (coverageOnly) {
  const covArgs = ["coverage", entry];
  const r = spawnSync(SCRIPTC, covArgs, { encoding: "utf8", cwd: ROOT, timeout: 1_500_000 });
  process.stdout.write(`${r.stdout ?? ""}${r.stderr ?? ""}`);
  process.exit(r.status ?? 1);
}
const exe = join(SCRATCH, "gds2js.exe");
const build = spawnSync(SCRIPTC, ["build", entry, "-o", exe, "--strip"], { encoding: "utf8", cwd: ROOT, timeout: 2_400_000 });
process.stdout.write(`${build.stdout ?? ""}${build.stderr ?? ""}`);
if (build.status !== 0 || !existsSync(exe)) {
  console.error("\n还没编过去：SC 编号就是线索（对着报错站点的形状看），新增的围栏记得记一笔。");
  if (!keep) rmSync(SCRATCH, { recursive: true, force: true });
  process.exit(1);
}
console.log(`原生 CLI 出货：${exe}`);
if (!keep) rmSync(SCRATCH, { recursive: true, force: true });
